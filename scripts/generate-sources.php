<?php

declare(strict_types=1);

/**
 * Regenerates src/Source.php and src/SourceMap.php from the collectors' input schemas.
 *
 * Usage: php scripts/generate-sources.php /path/to/apify-news-scraper && composer cs:fix
 *
 * Every boolean input field of a collector that is not an analysis flag is a news source toggle.
 *
 * Disabled collectors are the cases commented out in src/Collector.php (`// case Name = 'key';`). Their SourceMap
 * entries, and the cases and labels of the sources no other collector offers, are written as comments.
 */
$repo = $argv[1] ?? null;

if ($repo === null || ! is_dir($repo.'/actors')) {
    fwrite(STDERR, "Usage: php scripts/generate-sources.php /path/to/apify-news-scraper\n");
    exit(1);
}

const ANALYSIS_FLAGS = [
    'with_sentiment', 'with_tags', 'with_summary', 'with_5w1h', 'with_language_detection', 'with_fix_text',
];

const DISABLED_NOTE = '// temporarily disabled: pending publication';

// Read the file, not Collector::cases(): the disabled cases must keep their place in the order
preg_match_all(
    '/^\h*(\/\/\h*)?case \w+ = \'([^\']+)\';/m',
    (string) file_get_contents(__DIR__.'/../src/Collector.php'),
    $matches,
    PREG_SET_ORDER,
);

/** @var array<string, bool> $collectors Whether each collector is enabled, by key. */
$collectors = [];

foreach ($matches as $match) {
    $collectors[$match[2]] = $match[1] === '';
}

/** @var array<string, list<string>> $byCollector */
$byCollector = [];
/** @var array<string, string> $labels */
$labels = [];
/** @var array<string, true> $enabled Sources offered by at least one enabled collector. */
$enabled = [];

foreach ($collectors as $collector => $isEnabled) {
    $path = "{$repo}/actors/collector-{$collector}/.actor/input_schema.json";
    $schema = json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);

    foreach ($schema['properties'] as $key => $field) {
        if (($field['type'] ?? null) !== 'boolean' || in_array($key, ANALYSIS_FLAGS, true)) {
            continue;
        }

        $byCollector[$collector][] = $key;
        $labels[$key] ??= (string) ($field['title'] ?? $key);

        if ($isEnabled) {
            $enabled[$key] = true;
        }
    }
}

$caseName = static function (string $key): string {
    // PHP case names cannot start with a digit: spell the leading number out (5paisa -> FivePaisa)
    $key_ = preg_replace_callback(
        '/^(\d+)/',
        static fn (array $m): string => [5 => 'Five', 9 => 'Nine'][(int) $m[1]] ?? $m[1],
        $key
    );
    $name = str_replace(' ', '', ucwords(str_replace(['_', '-'], ' ', $key_)));

    if (! preg_match('/^[A-Za-z]/', $name)) {
        throw new RuntimeException("Source key '{$key}' does not map to a valid case name");
    }

    return $name;
};

$quote = static fn (string $value): string => "'".addcslashes($value, "'\\")."'";

// Comments out the lines of disabled entries, with one note in front of each consecutive run of them
$render = static function (array $entries): string {
    $out = '';
    $inDisabled = false;

    foreach ($entries as [$isEnabled, $indent, $lines]) {
        if (! $isEnabled && ! $inDisabled) {
            $out .= $indent.DISABLED_NOTE."\n";
        }

        $inDisabled = ! $isEnabled;

        foreach ($lines as $line) {
            $out .= $indent.($isEnabled ? '' : '// ').$line."\n";
        }
    }

    return $out;
};

$sources = array_keys($labels);
$names = [];

foreach ($sources as $key) {
    $name = $caseName($key);

    if (isset($names[$name])) {
        throw new RuntimeException("Source keys '{$names[$name]}' and '{$key}' both map to case {$name}");
    }

    $names[$name] = $key;
}

$enum = "<?php\n\ndeclare(strict_types=1);\n\nnamespace GlobalNewsScraper;\n\n";
$enum .= "use GlobalNewsScraper\\Support\\SourceLanguages;\nuse GlobalNewsScraper\\Support\\SourceLookup;\n\n";
$enum .= "// Generated by scripts/generate-sources.php. Do not edit by hand.\n\n";
$enum .= "/**\n * A news source that can be switched on. The value is the input field of the collector Actors.\n */\n";
$enum .= "enum Source: string\n{\n";

$cases = [];

foreach ($names as $name => $key) {
    $cases[] = [isset($enabled[$key]), '    ', ["case {$name} = {$quote($key)};"]];
}

$enum .= $render($cases);

$enum .= <<<'PHP'

    /**
     * Display name of the outlet.
     */
    public function label(): string
    {
        return SourceMap::LABELS[$this->value];
    }

    /**
     * The source with this display name (`label()`), ignoring case and surplus spaces. Null when there is none, or
     * when several sources have the name (e.g. `The Guardian`); an exact spelling wins over other case variants.
     * Accents count: `Excelsior` does not find `Excélsior`.
     */
    public static function fromLabel(string $label): ?self
    {
        return SourceLookup::fromLabel($label);
    }

    /**
     * All sources whose display name or key contains the text, ignoring case: those named exactly like it first,
     * the rest in the order of the cases. Empty for a blank query.
     *
     * @return list<self>
     */
    public static function search(string $query): array
    {
        return SourceLookup::search($query);
    }

    /**
     * Collectors that offer this source.
     *
     * @return list<Collector>
     */
    public function collectors(): array
    {
        $collectors = [];

        foreach (SourceMap::BY_COLLECTOR as $collector => $sources) {
            if (in_array($this->value, $sources, true)) {
                $collectors[] = Collector::from($collector);
            }
        }

        return $collectors;
    }

    /**
     * The language of the outlet as a source group, e.g. `SourceGroup::Spanish`.
     */
    public function language(): SourceGroup
    {
        return SourceLanguages::of($this);
    }
}

PHP;

$map = "<?php\n\ndeclare(strict_types=1);\n\nnamespace GlobalNewsScraper;\n\n";
$map .= "// Generated by scripts/generate-sources.php. Do not edit by hand.\n\n";
$map .= "/**\n * @internal\n */\nfinal class SourceMap\n{\n";
$map .= "    /** @var array<string, list<string>> Source keys offered by each collector, in input schema order. */\n";
$map .= "    public const BY_COLLECTOR = [\n";

$blocks = [];

foreach ($byCollector as $collector => $keys) {
    $lines = ["{$quote($collector)} => ["];

    foreach ($keys as $key) {
        $lines[] = "    {$quote($key)},";
    }

    $lines[] = '],';
    $blocks[] = [$collectors[$collector], '        ', $lines];
}

$map .= $render($blocks);
$map .= "    ];\n\n    /** @var array<string, string> */\n    public const LABELS = [\n";
$entries = [];

foreach ($labels as $key => $label) {
    $entries[] = [isset($enabled[$key]), '        ', ["{$quote($key)} => {$quote($label)},"]];
}

$map .= $render($entries);
$map .= "    ];\n}\n";

file_put_contents(__DIR__.'/../src/Source.php', $enum);
file_put_contents(__DIR__.'/../src/SourceMap.php', $map);

$active = count(array_filter($collectors));

echo count($enabled)." sources, {$active} collectors (disabled: ".(count($collectors) - $active).' collectors, '
    .(count($sources) - count($enabled))." sources)\n";
